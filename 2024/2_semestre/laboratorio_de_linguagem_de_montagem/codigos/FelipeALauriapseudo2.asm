DATA_SEG SEGMENT
    VAR1 EQU 4
    NUM1 DB VAR1
    NUM2 DB 2
    RESULTADO DB 0
    
DATA_SEG ENDS

CODE_SEG SEGMENT
    ASSUME CS:CODE_SEG, DS:DATA_SEG  

START:
    ORG 1000H
    MOV AL, VAR1
    NOP
    ADD AL, NUM2
    NOP
    MOV RESULTADO, AL
    ADD AL, 30H
    MOV DL, AL
    ADD AH, 02H
    INT 21h

CODE_SEG ENDS